import { accessibilityProblems, expect, openItem, signIn, state, test } from './state'

test('publishes an attachment with the chosen Creative Commons license', async ({ page, request }, info) => {
  const title = `Publication ${info.project.name}`
  const headers = { 'Zotero-API-Key': state().key }
  const created = await request.post('/users/1/items', { headers, data: [{ itemType: 'book', title }] })
  expect(created.ok()).toBe(true)
  const body = await created.json()
  expect(body.failed).toEqual({})
  const key = body.successful['0'].key as string
  await signIn(page)
  await openItem(page, title)
  const attach = page.locator('.detail').getByRole('button', { name: 'Add Attachment', exact: true })
  await attach.scrollIntoViewIfNeeded()
  await expect(async () => {
    if ((await attach.getAttribute('aria-expanded')) !== 'true') await attach.click()
    await expect(page.getByRole('menu', { name: 'Add Attachment' })).toBeVisible({ timeout: 500 })
  }).toPass()
  const bytes = Buffer.from(`%PDF-1.7\n${title}\n`)
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: 'Attach File…', exact: true }).click()
  await (await chooser).setFiles({ name: 'paper.pdf', mimeType: 'application/pdf', buffer: bytes })
  await expect(page.locator('.detail__children').getByText('PDF', { exact: true })).toBeVisible()
  await page.locator('.detail').getByRole('button', { name: 'Add to My Publications…', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByRole('checkbox', { name: 'Include files', exact: true }).check()
  await dialog.getByRole('checkbox', { name: 'I created this work and have the rights to distribute the files included.', exact: true }).check()
  await dialog.getByRole('button', { name: 'Next: Sharing', exact: true }).click()
  await dialog.getByRole('group', { name: 'Would you like to allow your work to be shared by others?', exact: true })
    .getByRole('radio', { name: 'Yes, under a Creative Commons license', exact: true }).check()
  await dialog.getByRole('button', { name: 'Next: Choose a License', exact: true }).click()
  await dialog.getByRole('group', { name: 'Allow adaptations of your work to be shared?', exact: true })
    .getByRole('radio', { name: 'Yes, as long as others share alike', exact: true }).check()
  await dialog.getByRole('group', { name: 'Allow commercial uses of your work?', exact: true })
    .getByRole('radio', { name: 'No', exact: true }).check()
  await expect(dialog.locator('.publish__license')).toContainText('CC BY-NC-SA')
  await page.screenshot({ path: info.outputPath('publication.png'), fullPage: true })
  expect(await accessibilityProblems(page)).toEqual([])
  await dialog.getByRole('button', { name: 'Add to My Publications', exact: true }).click()
  await expect(dialog).toBeHidden()
  const stored = async (path: string) => (await (await request.get(path, { headers })).json())
  const license = 'Creative Commons Attribution-NonCommercial-ShareAlike 4.0 International License'
  expect((await stored(`/users/1/items/${key}`)).data).toMatchObject({ inPublications: true, rights: license })
  const [file] = await stored(`/users/1/items/${key}/children`)
  expect(file.data).toMatchObject({ inPublications: true, itemType: 'attachment' })
  const download = await request.get(`/users/1/items/${file.key}/file`, { headers })
  expect(download.ok()).toBe(true)
  expect(await download.body()).toEqual(bytes)
})
