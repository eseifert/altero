import { accessibilityProblems, expect, openItem, PASSWORD, signIn, state, test } from './state'

test.use({ locale: 'es-ES' })

test('uses formal Spanish when issuing a key and explaining import and profile settings', async ({ page }) => {
  await signIn(page)
  await expect(page.locator('html')).toHaveAttribute('lang', 'es')
  await page.goto('/app/settings/keys')
  await page.locator('summary').filter({ hasText: 'Crear una clave' }).click()
  await page.getByRole('textbox', { name: '¿Para qué es?', exact: true }).fill('Spanish wording check')
  await page.getByLabel('Contraseña actual', { exact: true }).fill(PASSWORD)
  await page.getByRole('button', { name: 'Crear la clave', exact: true }).click()
  await expect(page.locator('.section-panel__notice')).toHaveText('Clave creada. Cópiela ahora: no se mostrará de nuevo.')
  await expect(page.locator('.settings__issued')).toContainText('Cópiela ahora. No se mostrará de nuevo.')
  expect(await accessibilityProblems(page)).toEqual([])

  await page.goto('/app/settings/migrate')
  await expect(page.locator('.settings__steps')).toContainText('Permítale leer su biblioteca personal y guárdela.')
  await page.getByRole('checkbox').check()
  await expect(page.getByRole('main').getByRole('status')).toHaveText(
    'Todo lo que hay en su biblioteca aquí se elimina primero, archivos incluidos, y no hay papelera que lo recoja.',
  )
  expect(await accessibilityProblems(page)).toEqual([])
  await page.goto('/app/u/ada')
  await expect(page.locator('.profile__own')).toContainText('Esta es su página pública.')
  expect(await accessibilityProblems(page)).toEqual([])
})

test('publishes a file using the formally worded licence questions', async ({ page, request }, info) => {
  const title = `Spanish publication ${info.project.name}`
  const headers = { 'Zotero-API-Key': state().key }
  const created = await request.post('/users/1/items', { headers, data: [{ itemType: 'book', title }] })
  expect(created.ok()).toBe(true)
  const body = await created.json()
  expect(body.failed).toEqual({})
  const key = body.successful['0'].key as string
  await signIn(page)
  await openItem(page, title)
  const attach = page.locator('.detail').getByRole('button', { name: 'Añadir adjunto', exact: true })
  await attach.scrollIntoViewIfNeeded()
  await expect(async () => {
    if ((await attach.getAttribute('aria-expanded')) !== 'true') await attach.click()
    await expect(page.getByRole('menu', { name: 'Añadir adjunto' })).toBeVisible({ timeout: 500 })
  }).toPass()
  const bytes = Buffer.from(`%PDF-1.7\n${title}\n`)
  const chooser = page.waitForEvent('filechooser')
  await page.getByRole('menuitem', { name: 'Adjuntar archivo…', exact: true }).click()
  await (await chooser).setFiles({ name: 'paper.pdf', mimeType: 'application/pdf', buffer: bytes })
  await expect(page.locator('.detail__children').getByText('PDF', { exact: true })).toBeVisible()
  await page.locator('.detail').getByRole('button', { name: 'Añadir a Mis publicaciones…', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('Añada únicamente trabajos que haya creado usted mismo')
  await dialog.getByRole('checkbox', { name: 'Incluir archivos', exact: true }).check()
  await dialog.getByRole('checkbox', { name: 'Yo creé este trabajo y tengo los derechos para distribuir los archivos incluidos.', exact: true }).check()
  await dialog.getByRole('button', { name: 'Siguiente: Compartir', exact: true }).click()
  await expect(dialog.getByRole('heading')).toHaveText('Elija cómo se puede compartir su trabajo')
  await dialog.getByRole('group', { name: '¿Quiere permitir que otros compartan su trabajo?', exact: true })
    .getByRole('radio', { name: 'Sí, bajo una licencia Creative Commons', exact: true }).check()
  await dialog.getByRole('button', { name: 'Siguiente: Elija una licencia', exact: true }).click()
  await expect(dialog.getByRole('heading')).toHaveText('Elija una licencia Creative Commons')
  await dialog.getByRole('group', { name: '¿Permitir que se compartan adaptaciones de su trabajo?', exact: true })
    .getByRole('radio', { name: 'Sí, siempre que se comparta bajo la misma licencia', exact: true }).check()
  await dialog.getByRole('group', { name: '¿Permitir el uso comercial de su trabajo?', exact: true })
    .getByRole('radio', { name: 'No', exact: true }).check()
  await expect(dialog.locator('.publish__license')).toContainText('CC BY-NC-SA')
  await expect(dialog).toContainText('aunque más adelante elija condiciones diferentes')
  await page.screenshot({ path: info.outputPath('spanish-publication.png'), fullPage: true })
  expect(await accessibilityProblems(page)).toEqual([])
  await dialog.getByRole('button', { name: 'Añadir a Mis publicaciones', exact: true }).click()
  await expect(dialog).toBeHidden()
  const stored = async (path: string) => (await (await request.get(path, { headers })).json())
  const license = 'Creative Commons Attribution-NonCommercial-ShareAlike 4.0 International License'
  expect((await stored(`/users/1/items/${key}`)).data).toMatchObject({ inPublications: true, rights: license })
  const [file] = await stored(`/users/1/items/${key}/children`)
  expect(file.data).toMatchObject({ inPublications: true, itemType: 'attachment' })
  const download = await request.get(`/users/1/items/${file.key}/file`, { headers })
  expect(download.ok()).toBe(true)
  expect(await download.body()).toEqual(bytes)
})
